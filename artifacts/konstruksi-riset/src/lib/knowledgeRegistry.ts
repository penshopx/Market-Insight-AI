export function getRelatedSources(sourceId: string): KnowledgeAsset[] {
  const asset = KNOWLEDGE_REGISTRY.find((a) => a.sourceId === sourceId);
  if (!asset) return [];
  return KNOWLEDGE_REGISTRY.filter((a) => asset.relatedSources.includes(a.sourceId));
}

