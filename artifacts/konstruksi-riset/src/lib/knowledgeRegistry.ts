export interface KnowledgeAsset {
  sourceId: string;                    // GOV-LPJK-001
  nama: string;                        // nama pendek
  namaResmi: string;                   // nama lengkap resmi
  url: string;
  group: SourceGroup;
  domainIndustri: DomainIndustri[];
  businessLifecycle: BusinessLifecycle[];
  otoritas: SourceAuthority;
  jenisKonten: string[];               // Regulasi, Tender, Standar, ...
  updateFrequency: UpdateFrequency;
  integrationLevel: IntegrationLevel;
  apiAvailable: ApiAvailability;
  crawlingStatus: CrawlingStatus;
  prioritasCrawl: string;              // "setiap 6 jam", "harian", dll
  businessValue: number;               // 1-10
  aiAgents: string[];                  // AI yang menggunakan
  aiOutput: string[];                  // output yang dihasilkan
  relatedSources: string[];            // sourceId yang terkait
  catatan: string;
  /** ISO-8601 date string of last content update — optional, used for freshness analytics */
  lastUpdated?: string;
  /** High-level content category for revenue modelling — optional */
  category?: KnowledgeCategory;
}

