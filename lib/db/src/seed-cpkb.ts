async function seed() {
  console.log(`Seeding ${cpkbProblems.length} CPKB problems...`);

  // Clear existing pain points first
  await db.delete(painPointsTable);
  console.log("Cleared existing pain points.");

  let seeded = 0;
  for (const p of cpkbProblems) {
    await db.insert(painPointsTable).values({
      problemId: p.problemId,
      domain: p.domain,
      subdomain: p.subdomain,
      painScore: p.painScore,
      affectedRoles: p.affectedRoles,
      description: p.description,
      rootCause: p.rootCause,
      businessImpact: p.businessImpact,
      sdmGap: p.sdmGap,
      manualSolution: p.manualSolution,
      digitalSolution: p.digitalSolution,
      aiSolution: p.aiSolution,
      linkedAiAgent: p.linkedAiAgent,
      serviceOpportunity: p.serviceOpportunity,
      crossReferences: p.crossReferences,
      segment: p.segment,
      frequency: p.frequency,
      priority: p.priority,
      category: p.category ?? null,
      productIdea: null,
      status: p.status,
    });
    seeded++;
    if (seeded % 10 === 0) console.log(`  ${seeded}/${cpkbProblems.length} seeded...`);
  }

  console.log(`✅ Done! Seeded ${seeded} CPKB problems.`);
  process.exit(0);
}

seed().catch((e) => { console.error(e); process.exit(1); });
